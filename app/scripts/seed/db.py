"""Seed script to populate initial dummy data for User and Post models.

Usage:
    python app/scripts/seed/db.py
    # or
    python -m app.scripts.seed.db
"""

import sys
from pathlib import Path

# Ensure project root is in sys.path when running script directly
sys.path.append(str(Path(__file__).resolve().parents[3]))

from sqlalchemy import select
from app.db.session import SessionLocal
from app.models.user import User
from app.models.post import Post


# Dummy data definitions
DUMMY_USERS = [
    {
        "name": "Alice Johnson",
        "email": "alice@example.com",
        "age": 28,
    },
    {
        "name": "Bob Smith",
        "email": "bob@example.com",
        "age": 34,
    },
    {
        "name": "Charlie Brown",
        "email": "charlie@example.com",
        "age": 22,
    },
]

DUMMY_POSTS = [
    {
        "title": "Getting Started with FastAPI",
        "content": "FastAPI is a modern, fast web framework for building APIs with Python 3.8+.",
        "is_published": True,
    },
    {
        "title": "Mastering SQLAlchemy 2.0 & Alembic",
        "content": "Learn how DeclarativeBase and autogenerated migrations simplify database workflows.",
        "is_published": True,
    },
    {
        "title": "Upcoming Architecture Draft",
        "content": "A sneak peek into upcoming features and roadmap for the project.",
        "is_published": False,
    },
]


def seed_users(db) -> int:
    """Seed users, skipping existing emails to prevent duplicate errors."""
    added_count = 0
    for user_data in DUMMY_USERS:
        # Check if user already exists
        existing = db.scalar(
            select(User).where(User.email == user_data["email"])
        )
        if not existing:
            user = User(**user_data)
            db.add(user)
            added_count += 1
            print(f"  + Added user: {user_data['name']} ({user_data['email']})")
        else:
            print(f"  ~ Skipped user (already exists): {user_data['email']}")
    return added_count


def seed_posts(db) -> int:
    """Seed posts, skipping existing titles to prevent duplicate records."""
    added_count = 0
    for post_data in DUMMY_POSTS:
        # Check if post with the same title already exists
        existing = db.scalar(
            select(Post).where(Post.title == post_data["title"])
        )
        if not existing:
            post = Post(**post_data)
            db.add(post)
            added_count += 1
            print(f"  + Added post: '{post_data['title']}'")
        else:
            print(f"  ~ Skipped post (already exists): '{post_data['title']}'")
    return added_count


def main() -> None:
    print("🌱 Starting database seeding...")
    db = SessionLocal()

    try:
        print("\n[Seeding Users]")
        new_users = seed_users(db)

        print("\n[Seeding Posts]")
        new_posts = seed_posts(db)

        db.commit()
        print(f"\n✅ Seeding complete! Added {new_users} user(s) and {new_posts} post(s).")
    except Exception as e:
        db.rollback()
        print(f"\n❌ Seeding failed: {e}")
        raise
    finally:
        db.close()


if __name__ == "__main__":
    main()

